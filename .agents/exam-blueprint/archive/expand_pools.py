def expand_list(pools: dict, cat: str, extras: list[str], seen: set[str], limit: int) -> int:
    n = 0
    add = append_curated if cat in TOPIC_CATS else append_n2
    for item in extras:
        if len(pools.get(cat, [])) >= limit:
            break
        if add(pools, cat, item, seen):
            n += 1
    return n


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    pools = json.loads(POOLS.read_text(encoding="utf-8"))
    seen = existing_heads(pools)
    added: dict[str, int] = {}

    added["kanji_reading"] = expand_kanji(pools, seen, TARGETS["kanji_reading"])
    for cat in ("orthography", "context_words", "paraphrase", "usage"):
        added[cat] = expand_vocab_cat(pools, cat, seen, TARGETS[cat])

    added["word_formation"] = expand_list(
        pools, "word_formation", FORMATION_EXTRA, seen, TARGETS["word_formation"])
    added["reading_topics"] = expand_list(
        pools, "reading_topics", READING_TOPICS_EXTRA, seen, TARGETS["reading_topics"])
    added["listening_scenarios"] = expand_list(
        pools, "listening_scenarios", LISTENING_EXTRA, seen, TARGETS["listening_scenarios"])
    added["quick_response"] = expand_list(
        pools, "quick_response", QR_EXTRA, seen, TARGETS["quick_response"])

    for cat, n in added.items():
        print(f"  {cat}: +{n} -> {len(pools.get(cat, []))} total")

    if args.dry_run:
        print("dry-run: pools.json not written")
        return

    POOLS.write_text(json.dumps(pools, ensure_ascii=False, indent=1) + "\n",
                     encoding="utf-8")
    print(f"wrote {POOLS}")


if __name__ == "__main__":
    main()
