def append_curated(pools: dict, cat: str, item: str, seen: set[str]) -> bool:
    """Append setting/topic strings curated for N2 mocks (no OpenJLPT lookup)."""
    h = head(item)
    if h in seen or item in pools.get(cat, []):
        return False
    pools.setdefault(cat, []).append(item)
    seen.add(h)
    return True


def append_n2(pools: dict, cat: str, item: str, seen: set[str]) -> bool:
    h = head(item)
    if h in seen or item in pools.get(cat, []):
        return False
    res = classify_one(item, cat)
    if res["level"] != "N2":
        return False
    pools.setdefault(cat, []).append(item)
    seen.add(h)
    return True


def expand_kanji(pools: dict, seen: set[str], limit: int) -> int:
    n = 0
    for row in load_kanji_n2():
        if len(pools.get("kanji_reading", [])) >= limit:
            break
        c = row.get("character", "")
        if not c or c in seen:
            continue
        kun = (row.get("kunyomi") or [""])[0]
        on = (row.get("onyomi") or [""])[0]
        reading = kun if kun and re.search(r"[\u3040-\u30ff]", kun) else on.lower()
        item = f"{c}({reading})" if reading else c
        if append_n2(pools, "kanji_reading", item, seen):
            n += 1
    return n


def expand_vocab_cat(pools: dict, cat: str, seen: set[str], limit: int) -> int:
    n = 0
    for row in load_vocab_n2():
        if len(pools.get(cat, [])) >= limit:
            break
        w = (row.get("word") or "").strip()
        if not w or head(w) in seen:
            continue
        if cat == "orthography" and not re.search(r"[\u4e00-\u9fff]{2,}", w):
            continue
        if cat in ("context_words", "usage") and len(w) < 2:
            continue
        if append_n2(pools, cat, w, seen):
            n += 1
    return n


